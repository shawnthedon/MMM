import assert from 'node:assert/strict';
import { inspectJsonl, JSONL_MAX_BYTES, JSONL_MAX_ROWS } from '../src/copilot/jsonlInspection.js';
assert.deepEqual(inspectJsonl('{"text":"hello"}\n{"text":"world"}\n'), { ok: true, rows: 2, errors: [] });
assert.equal(inspectJsonl('').ok, false);
assert.equal(inspectJsonl(null).ok, false);
assert.match(inspectJsonl('{"text":}\n').errors[0], /Line 1: invalid JSON/);
assert.match(inspectJsonl('[1,2]').errors[0], /expected a JSON object/);
assert.equal(inspectJsonl('😀'.repeat(JSONL_MAX_BYTES / 3)).ok, false);
assert.match(inspectJsonl('{}\n'.repeat(JSONL_MAX_ROWS + 1)).errors[0], /10,000-row/);
const errors = inspectJsonl('not-json\n'.repeat(20)).errors;
assert.equal(errors.length, 5);
assert(!JSON.stringify(errors).includes('not-json'), 'invalid private record content must not be echoed');
const { getState } = await import('../src/core.js');
const { inspectDataset } = await import('../src/copilot/orchestrator.js');
getState().files = [{ path: 'samples/example.jsonl', content: '{\"text\":\"ok\"}', size: 13 }];
const report = inspectDataset();
assert.equal(report.checks.find((c) => c.label === 'Inline JSONL syntax').status, 'ok');
assert.equal(report.checks.find((c) => c.label === 'Training readiness').status, 'bad');
assert.match(report.verdict, /not a dataset audit/);
console.log('TRAINING JSONL INSPECTION: object syntax, invalid rows, bounds and error redaction passed');
